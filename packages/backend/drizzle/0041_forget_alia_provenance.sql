-- `pre`, and why this is not in 0042 with the rest: the image this rollout
-- ships, and the frontend that goes out with it, no longer know `'alia'`. The
-- frontend parses a show's `sources` against the narrowed vocabulary, so a row
-- still holding `'alia'` would fail to parse for those two shows from the
-- moment the new client is live. Deleting the rows first is safe for the
-- previous image too: it reads provenance only to serialize it, and nothing
-- calls the `aliaSeriesId` field that wrote it any more. The CHECK is narrowed
-- in 0042, after the previous image has drained.

DELETE FROM "podcast_sources" WHERE "provider" = 'alia';
